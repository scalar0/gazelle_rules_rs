func TestConfiguredScope(t *testing.T) {
	for _, scope := range []string{"crates", "project/components"} {
		fs := flag.NewFlagSet("test", flag.ContinueOnError)
		exclude := fs.String("exclude", "", "")
		e := &extension{}
		e.RegisterFlags(fs, "update", nil)
		if err := fs.Set("rules_rs_crate_scope", scope); err != nil {
			t.Fatal(err)
		}
		if e.scope != scope || *exclude != scope+"/*/*" || !inScope(scope, scope+"/example") {
			t.Fatal("The scope flag must configure crate discovery and nested exclusions.")
		}
		if inScope(scope, scope+"/example/nested") || inScope(scope, "other/example") {
			t.Fatal("Crate discovery escaped the configured scope.")
		}
		for _, invalid := range []string{"", ".", "..", "../crates", "/tmp/crates", "crates/../outside", "crates/*", "crates/"} {
			if err := fs.Set("rules_rs_crate_scope", invalid); err == nil {
				t.Errorf("Accepted invalid scope %q", invalid)
			}
		}
	}
	if err := checkScope(t.TempDir(), "", "", []string{"."}); err == nil {
		t.Fatal("Generation must require an explicit scope.")
	}
}

func TestScopeArguments(t *testing.T) {
	root := t.TempDir()
	for _, rel := range []string{"crates", "crates/probe"} {
		if err := os.MkdirAll(filepath.Join(root, rel), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := checkScope(root, root, "crates", []string{rel}); err != nil {
			t.Fatal(err)
		}
	}
	for _, rel := range []string{".", "rules_rs", "fixtures", "crates/probe/src", "other/crates"} {
		if err := checkScope(root, root, "crates", []string{filepath.Join(root, rel)}); err == nil {
			t.Errorf("Accepted out-of-scope path: %s", rel)
		}
	}
	if err := checkScope(root, root, "crates", nil); err == nil {
		t.Fatal("Implicit workspace-wide generation must fail.")
	}
}

