func TestMultipleScopes(t *testing.T) {
	root := t.TempDir()
	scopes := "first/crates,second/crates"
	fs := flag.NewFlagSet("test", flag.ContinueOnError)
	var excludes []string
	fs.Func("exclude", "", func(value string) error { excludes = append(excludes, value); return nil })
	e := &extension{}
	e.RegisterFlags(fs, "update", nil)
	if err := fs.Set("rules_rs_crate_scope", scopes); err != nil {
		t.Fatal(err)
	}
	if strings.Join(excludes, ",") != "first/crates/*/*,second/crates/*/*" {
		t.Fatal(excludes)
	}
	for _, rel := range []string{"first/crates/probe", "second/crates/support"} {
		if err := os.MkdirAll(filepath.Join(root, rel), 0o755); err != nil {
			t.Fatal(err)
		}
		if !inScope(scopes, rel) {
			t.Fatal(rel)
		}
		if err := checkScope(root, root, scopes, []string{rel}); err != nil {
			t.Fatal(err)
		}
	}
	for _, rel := range []string{"first/crates/probe/src", "second/fixtures/probe", "third/crates/probe"} {
		if inScope(scopes, rel) {
			t.Fatal(rel)
		}
	}
	for _, invalid := range []string{"first/crates,", "first/crates,../outside", ",second/crates"} {
		if err := fs.Set("rules_rs_crate_scope", invalid); err == nil {
			t.Fatalf("Accepted %q", invalid)
		}
	}
}

func TestMigrationSettings(t *testing.T) {
	testOnly := true
	opts := settings{
		TestTimeout: "long",
		TestOnly:    &testOnly,
		DepOverride: &dependencyOverride{Prefix: "@crates//:fixture", Target: "//fixtures:fixture"},
	}
	root := t.TempDir()
	pkg := cargoPackage{Name: "probe", Targets: []cargoTarget{
		{Name: "probe", Kind: []string{"lib"}, Source: filepath.Join(root, "crates/probe/src/lib.rs")},
		{Name: "integration", Kind: []string{"test"}, Source: filepath.Join(root, "crates/probe/tests/integration.rs")},
	}}
	rules, err := generate(root, "crates/probe", pkg, opts)
	if err != nil {
		t.Fatal(err)
	}
	output := rendered(rules)
	for _, want := range []string{`timeout = "long"`, `testonly = True`, `dep.startswith("@crates//:fixture")`, `label.startswith("@crates//:fixture")`, `"//fixtures:fixture"`} {
		if !strings.Contains(output, want) {
			t.Fatalf("Missing %s in %s", want, output)
		}
	}
	for _, invalid := range []string{"rules_rs_test_timeout long", "rules_rs_testonly true", "rules_rs_dep_override @crates//:fixture //fixtures:fixture"} {
		file, err := rule.LoadData("BUILD.bazel", "crates/probe", []byte("# gazelle:"+invalid+"\n"))
		if err != nil {
			t.Fatal(err)
		}
		if err := rejectLegacyDirectives(file); err == nil {
			t.Fatalf("Accepted %s", invalid)
		}
	}
}

func TestSettingsPreserveContextSelections(t *testing.T) {
	r := newRule("rust_library", "probe")
	setAttr(r, "deps", rule.ExprFromValue(rule.SelectStringListValue{
		"//conditions:default": {"@crates//:fixture-1.0.0"},
		"//platform:linux":     {"@crates//:other-1.0.0"},
	}))
	alias := newRule("alias", "probe-build-script")
	setAttr(alias, "actual", ":probe-build-script-context")
	testOnly := true
	applySettings([]*rule.Rule{r, alias}, settings{
		DepOverride: &dependencyOverride{Prefix: "@crates//:fixture", Target: "//fixtures:fixture"},
		TestOnly:    &testOnly,
	})
	output := rendered([]*rule.Rule{r, alias})
	if !strings.Contains(output, "deps = select({") || strings.Contains(output, "for dep in select(") {
		t.Fatalf("The override must preserve select branches: %s", output)
	}
	if strings.Count(output, "testonly = True") != 2 {
		t.Fatal(output)
	}
}

func TestUnitSourceShapeTransitions(t *testing.T) {
	for _, useCrate := range []bool{true, false} {
		file, err := rule.LoadData("BUILD.bazel", "crates/probe", []byte(`
# Generated by rules_rs Gazelle.
rust_test(name = "probe-unit-tests", crate = ":probe", srcs = glob(["src/**/*.rs"]), crate_root = "src/lib.rs", crate_name = "probe",
visibility = ["//custom:clients"], # keep
timeout = "long", # keep
)
`))
		if err != nil {
			t.Fatal(err)
		}
		generate := func() *rule.Rule {
			fresh := newRule("rust_test", "probe-unit-tests")
			if useCrate {
				setAttr(fresh, "crate", ":probe")
			} else {
				setAttr(fresh, "srcs", librarySources("src/lib.rs"))
				setAttr(fresh, "crate_root", "src/lib.rs")
				setAttr(fresh, "crate_name", "probe_context")
			}
			return fresh
		}
		merge := func() {
			result, err := reconcile(file, []*rule.Rule{generate()})
			if err != nil {
				t.Fatal(err)
			}
			merger.MergeFile(file, result.Empty, result.Gen, merger.PreResolve, (&extension{}).Kinds(), nil)
			merger.MergeFile(file, nil, result.Gen, merger.PostResolve, (&extension{}).Kinds(), nil)
		}
		merge()
		unit := file.Rules[0]
		if useCrate {
			for _, key := range []string{"srcs", "crate_root", "crate_name"} {
				if unit.Attr(key) != nil {
					t.Fatalf("The crate unit retains %s", key)
				}
			}
		} else if unit.Attr("crate") != nil {
			t.Fatal("The context unit retains crate")
		}
		if unit.Attr("visibility") == nil || unit.AttrString("timeout") != "long" {
			t.Fatal("The merge removed handwritten attributes")
		}
		first := string(file.Format())
		merge()
		if first != string(file.Format()) {
			t.Fatal("The repeated merge changed the rule")
		}
	}
}
