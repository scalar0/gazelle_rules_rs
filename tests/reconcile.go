func TestHandwrittenCollision(t *testing.T) {
	file, err := rule.LoadData("BUILD.bazel", "crates/probe", []byte(`
rust_library(name = "probe", srcs = ["handwritten.rs"])
`))
	if err != nil {
		t.Fatal(err)
	}
	before := string(file.Format())
	_, err = reconcile(file, []*rule.Rule{newRule("rust_library", "probe")})
	if err == nil || !strings.Contains(err.Error(), "handwritten") {
		t.Fatalf("Expected a handwritten target conflict, got %v", err)
	}
	if string(file.Format()) != before {
		t.Fatal("Conflict detection changed the BUILD file.")
	}
}

func TestReconcileKindChangeAndDeletion(t *testing.T) {
	file, err := rule.LoadData("BUILD.bazel", "crates/probe", []byte(`
package(default_visibility = ["//custom:clients"])
filegroup(name = "resource", srcs = ["data.json"])
# Generated by rules_rs Gazelle.
rust_library(name = "probe", srcs = glob(["src/**/*.rs"]), deps = all_crate_deps(normal = True))
# Generated by rules_rs Gazelle.
rust_test(name = "probe-unit-tests", crate = ":probe", deps = all_crate_deps(normal_dev = True))
`))
	if err != nil {
		t.Fatal(err)
	}
	macro := newRule("rust_proc_macro", "probe")
	setAttr(macro, "srcs", librarySources("src/lib.rs"))
	result, err := reconcile(file, []*rule.Rule{macro})
	if err != nil {
		t.Fatal(err)
	}
	merger.MergeFile(file, result.Empty, result.Gen, merger.PreResolve, (&extension{}).Kinds(), nil)
	output := string(file.Format())
	for _, removed := range []string{"rust_library(", "rust_test(", "all_crate_deps"} {
		if strings.Contains(output, removed) {
			t.Fatalf("Stale rule data remains: %s", output)
		}
	}
	for _, retained := range []string{"//custom:clients", "filegroup(", "data.json", "rust_proc_macro("} {
		if !strings.Contains(output, retained) {
			t.Fatalf("Missing %q: %s", retained, output)
		}
	}
}

