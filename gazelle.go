const marker = "# Generated by rules_rs Gazelle."

var directives = []string{
	"rules_rs_library_compile_data", "rules_rs_unit_compile_data", "rules_rs_test_compile_data",
	"rules_rs_test_data", "rules_rs_build_compile_data", "rules_rs_build_data",
	"rules_rs_test_timeout", "rules_rs_testonly", "rules_rs_dep_override",
}

type extension struct {
	packages map[string]cargoPackage
	scope    string
}

func NewLanguage() language.Language { return &extension{} }
func (*extension) Name() string      { return "rules_rs" }
func (e *extension) RegisterFlags(fs *flag.FlagSet, _ string, _ *config.Config) {
	fs.Func("rules_rs_crate_scope", "Comma-separated workspace-relative directories that contain crate packages.", func(scopes string) error {
		for _, scope := range strings.Split(scopes, ",") {
			if scope == "" || scope == "." || scope == ".." || filepath.IsAbs(scope) || strings.HasPrefix(scope, "../") ||
				filepath.ToSlash(filepath.Clean(scope)) != scope || strings.ContainsAny(scope, "*?[\\") {
				return fmt.Errorf("rules_rs_crate_scope must contain clean workspace-relative directories")
			}
		}
		e.scope = scopes
		// Set exclusions before Gazelle configures its walk.
		for _, scope := range strings.Split(scopes, ",") {
			if err := fs.Set("exclude", scope+"/*/*"); err != nil {
				return err
			}
		}
		return nil
	})
}

func (e *extension) CheckFlags(fs *flag.FlagSet, c *config.Config) error {
	if err := checkScope(c.RepoRoot, c.WorkDir, e.scope, fs.Args()); err != nil {
		return err
	}
	var err error
	e.packages, err = readMetadata(c.RepoRoot, e.scope)
	return err
}

func checkScope(root, workDir, scope string, dirs []string) error {
	if scope == "" {
		return fmt.Errorf("set rules_rs_crate_scope before generation")
	}
	if len(dirs) == 0 {
		return fmt.Errorf("pass %s or an immediate crate directory", scope)
	}
	for _, dir := range dirs {
		abs := dir
		if !filepath.IsAbs(abs) {
			abs = filepath.Join(workDir, abs)
		}
		abs, err := filepath.EvalSymlinks(abs)
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, abs)
		if err != nil || (!slices.Contains(strings.Split(scope, ","), filepath.ToSlash(rel)) && !inScope(scope, filepath.ToSlash(rel))) {
			return fmt.Errorf("generation directory %q is outside the configured crate scope %q", dir, scope)
		}
	}
	return nil
}
func (*extension) KnownDirectives() []string { return directives }
func (e *extension) Configure(c *config.Config, rel string, f *rule.File) {
	if inScope(e.scope, rel) && f != nil {
		if err := rejectLegacyDirectives(f); err != nil {
			log.Fatal(fmt.Errorf("configure %s: %w", rel, err))
		}
	}
	if pkg, ok := e.packages[rel]; ok {
		c.Exts["rules_rs"] = pkg.Settings
	} else {
		c.Exts["rules_rs"] = settings{}
	}
}
func (*extension) Fix(*config.Config, *rule.File) {}
func (*extension) Kinds() map[string]rule.KindInfo {
	attrs := map[string]bool{}
	for _, key := range []string{"srcs", "crate", "crate_root", "crate_name", "edition", "aliases", "deps", "lint_config", "crate_features", "compile_data", "data", "tests", "tags", "rustc_flags", "rustc_env", "build_script_env", "version", "pkg_name", "visibility", "target_compatible_with", "actual", "use_libtest_harness", "timeout", "testonly"} {
		attrs[key] = true
	}
	kinds := map[string]rule.KindInfo{}
	for _, kind := range []string{"rust_library", "rust_proc_macro", "rust_binary", "rust_test", "cargo_build_script", "test_suite", "alias"} {
		kinds[kind] = rule.KindInfo{MergeableAttrs: attrs, NonEmptyAttrs: map[string]bool{"srcs": true, "crate": true, "tests": true, "actual": true}}
	}
	return kinds
}

func (*extension) Loads() []rule.LoadInfo {
	loads := []rule.LoadInfo{{Name: "@crates//:defs.bzl", Symbols: []string{"all_crate_deps", "aliases", "crate_name", "edition", "lint_config"}}}
	for _, kind := range []string{"rust_library", "rust_proc_macro", "rust_binary", "rust_test", "cargo_build_script"} {
		loads = append(loads, rule.LoadInfo{Name: "@rules_rs//rs:" + kind + ".bzl", Symbols: []string{kind}})
	}
	return loads
}

func (e *extension) GenerateRules(args language.GenerateArgs) language.GenerateResult {
	if !inScope(e.scope, args.Rel) {
		return language.GenerateResult{}
	}
	var rules []*rule.Rule
	if pkg, ok := e.packages[args.Rel]; ok {
		var err error
		rules, err = generate(args.Config.RepoRoot, args.Rel, pkg, args.Config.Exts["rules_rs"].(settings))
		if err == nil && pkg.Contexts != nil {
			rules, err = generateContexts(args.Rel, pkg, rules)
			if err == nil {
				applySettings(rules, args.Config.Exts["rules_rs"].(settings))
			}
		}
		if err != nil {
			log.Fatal(fmt.Errorf("generate %s: %w", args.Rel, err))
		}
	}
	result, err := reconcile(args.File, rules)
	if err != nil {
		log.Fatal(fmt.Errorf("generate %s: %w", args.Rel, err))
	}
	return result
}

// Reconcile changes only marked rules and rejects handwritten name conflicts.
func reconcile(file *rule.File, rules []*rule.Rule) (language.GenerateResult, error) {
	result := language.GenerateResult{Gen: rules, Imports: make([]interface{}, len(rules))}
	names := map[string]*rule.Rule{}
	for _, r := range rules {
		if names[r.Name()] != nil {
			return language.GenerateResult{}, fmt.Errorf("multiple Cargo targets map to %q", r.Name())
		}
		names[r.Name()] = r
	}
	if file == nil {
		return result, nil
	}
	kinds := (&extension{}).Kinds()
	for _, old := range file.Rules {
		owned := false
		for _, comment := range old.Comments() {
			owned = owned || comment == marker
		}
		fresh := names[old.Name()]
		if fresh != nil {
			if !owned {
				return language.GenerateResult{}, fmt.Errorf("target %q conflicts with a handwritten rule", old.Name())
			}
			if fresh.Kind() == old.Kind() {
				if old.Kind() == "rust_test" && !old.ShouldKeep() {
					for _, key := range []string{"srcs", "crate", "crate_root", "crate_name"} {
						if old.Attr(key) != nil && fresh.Attr(key) == nil {
							// Attribute keep comments belong to the assignment.
							comments := old.AttrComments(key)
							if !rule.ShouldKeep(&bzl.AssignExpr{Comments: *comments}) {
								old.DelAttr(key)
							}
						}
					}
				}
				continue
			}
			if old.ShouldKeep() {
				return language.GenerateResult{}, fmt.Errorf("target %q changes kind but has a keep comment", old.Name())
			}
		}
		if owned {
			empty := rule.NewRule(old.Kind(), old.Name())
			for key := range kinds[old.Kind()].MergeableAttrs {
				if old.Attr(key) != nil {
					empty.SetAttr(key, generatedExpr{})
				}
			}
			result.Empty = append(result.Empty, empty)
		}
	}
	return result, nil
}

