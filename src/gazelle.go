const marker = "# Generated by gazelle_rules_rs."

var directives = []string{
	"rules_rs_library_compile_data", "rules_rs_unit_compile_data", "rules_rs_test_compile_data",
	"rules_rs_test_data", "rules_rs_build_compile_data", "rules_rs_build_data",
	"rules_rs_test_timeout", "rules_rs_testonly", "rules_rs_dep_override",
}

type extension struct {
	handlers   []registeredHandler
	kinds      map[string]rule.KindInfo
	cfg        BackendConfig
	configPath string
	buildNames []string
	prepared   map[string][]*rule.Rule
	root       string
	packages   map[string]cargoPackage
	generated  []*rule.Rule
	scope      string
}

func NewV2() language.Language {
	result, err := New()
	if err != nil {
		panic(err)
	}
	return result
}
func (*extension) Name() string { return "rules_rs" }
func (e *extension) RegisterFlags(fs *flag.FlagSet, _ string, _ *config.Config) {
	fs.StringVar(&e.configPath, "rules_rs_config", "", "Backend configuration file generated from MODULE settings.")
	fs.Func("rules_rs_crate_scope", "Comma-separated workspace-relative directories that contain crate packages.", func(scopes string) error {
		for _, scope := range strings.Split(scopes, ",") {
			if scope == "" || scope == "." || scope == ".." || filepath.IsAbs(scope) || strings.HasPrefix(scope, "../") ||
				filepath.ToSlash(filepath.Clean(scope)) != scope || strings.ContainsAny(scope, "*?[\\") {
				return fmt.Errorf("rules_rs_crate_scope must contain clean workspace-relative directories")
			}
		}
		e.scope = scopes
		// Set exclusions before Gazelle configures its walk.
		for _, scope := range strings.Split(scopes, ",") {
			if err := fs.Set("exclude", scope+"/*/*"); err != nil {
				return err
			}
		}
		return nil
	})
}

func (e *extension) CheckFlags(fs *flag.FlagSet, c *config.Config) error {
	if e.scope != "" {
		if err := checkScope(c.RepoRoot, c.WorkDir, e.scope, fs.Args()); err != nil {
			return err
		}
	}
	if e.configPath == "" {
		return fmt.Errorf("set -rules_rs_config to the backend configuration file before generation")
	}
	var err error
	e.cfg, err = readBackendConfig(e.configPath)
	if err != nil {
		return err
	}
	e.root = c.RepoRoot
	e.buildNames = slices.Clone(c.ValidBuildFileNames)
	return nil
}

func checkScope(root, workDir, scope string, dirs []string) error {
	if scope == "" {
		return fmt.Errorf("set rules_rs_crate_scope before generation")
	}
	if len(dirs) == 0 {
		return fmt.Errorf("pass %s or an immediate crate directory", scope)
	}
	canonicalRoot, err := filepath.EvalSymlinks(root)
	if err != nil {
		return err
	}
	root = canonicalRoot
	for _, dir := range dirs {
		abs := dir
		if !filepath.IsAbs(abs) {
			abs = filepath.Join(workDir, abs)
		}
		abs, err := filepath.EvalSymlinks(abs)
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, abs)
		if err != nil || (!slices.Contains(strings.Split(scope, ","), filepath.ToSlash(rel)) && !inScope(scope, filepath.ToSlash(rel))) {
			return fmt.Errorf("generation directory %q is outside the configured crate scope %q", dir, scope)
		}
	}
	return nil
}
func (*extension) KnownDirectives() []string { return directives }
func (e *extension) Configure(ctx context.Context, args config.ConfigureArgs) error {
	c, rel, f := args.Config, args.Rel, args.File
	if err := ctx.Err(); err != nil {
		return err
	}
	if inScope(e.scope, rel) && f != nil {
		if err := rejectLegacyDirectives(f); err != nil {
			return errors.WithSeverity(errors.Critical, fmt.Errorf("configure %s: %w", rel, err))
		}
	}
	if pkg, ok := e.packages[rel]; ok {
		c.Exts["rules_rs"] = pkg.Settings
	} else {
		c.Exts["rules_rs"] = settings{}
	}
	return nil
}

func kindMap() map[string]rule.KindInfo {
	attrs := map[string]bool{}
	for _, key := range []string{"srcs", "crate", "crate_root", "crate_name", "edition", "aliases", "deps", "lint_config", "crate_features", "compile_data", "data", "tests", "tags", "rustc_flags", "rustc_env", "build_script_env", "version", "pkg_name", "visibility", "target_compatible_with", "actual", "use_libtest_harness", "timeout", "testonly", "args", "rustdoc_flags"} {
		attrs[key] = true
	}
	kinds := map[string]rule.KindInfo{}
	for _, kind := range []string{"rust_library", "rust_proc_macro", "rust_binary", "rust_test", "cargo_build_script", "test_suite", "alias", "rust_shared_library", "rust_static_library", "rust_dylib_library", "rust_doc_test"} {
		kinds[kind] = rule.KindInfo{MergeableAttrs: attrs, NonEmptyAttrs: map[string]bool{"srcs": true, "crate": true, "tests": true, "actual": true}}
	}
	return kinds
}

func (e *extension) Kinds() []rule.KindInfo {
	result := []rule.KindInfo{}
	for name, info := range e.registeredKinds() {
		info.Name = name
		if _, core := kindMap()[name]; core && name != "alias" && name != "test_suite" {
			info.LoadedFrom = label.New(e.rulesRepository(), "rs", name+".bzl")
			if name == "rust_doc_test" || name == "rust_dylib_library" {
				info.LoadedFrom = label.New("rules_rust", "rust", "defs.bzl")
			}
		}
		result = append(result, info)
	}
	for _, name := range []string{"all_crate_deps", "aliases", "crate_name", "edition", "lint_config"} {
		result = append(result, rule.KindInfo{Name: name, LoadedFrom: label.New(e.cratesRepository(), "", "defs.bzl")})
	}
	slices.SortFunc(result, func(a, b rule.KindInfo) int { return strings.Compare(a.Name, b.Name) })
	return result
}

var (
	_ language.Generator = (*extension)(nil)
	_ config.Configurer  = (*extension)(nil)
)

func (e *extension) Generate(ctx context.Context, args language.GenerateArgs) (language.GenerateResult, error) {
	if err := ctx.Err(); err != nil {
		return language.GenerateResult{}, err
	}
	if e.scope != "" && !inScope(e.scope, args.Rel) {
		return language.GenerateResult{}, nil
	}
	rules := e.prepared[args.Rel]
	if rules == nil && args.File != nil {
		owned := false
		for _, r := range args.File.Rules {
			owned = owned || slices.Contains(r.Comments(), marker)
		}
		if !owned {
			return language.GenerateResult{}, nil
		}
	}

	result, err := reconcileKinds(args.File, rules, e.registeredKinds())
	if err != nil {
		return language.GenerateResult{}, errors.WithSeverity(errors.Critical, fmt.Errorf("generate %s: %w", args.Rel, err))
	}
	e.generated = append(e.generated, result.Gen...)
	return result, nil
}

func reconcileKinds(file *rule.File, rules []*rule.Rule, kinds map[string]rule.KindInfo) (language.GenerateResult, error) {
	result := language.GenerateResult{Gen: rules, Imports: make([]interface{}, len(rules))}
	names := map[string]*rule.Rule{}
	for _, r := range rules {
		if names[r.Name()] != nil {
			return language.GenerateResult{}, fmt.Errorf("multiple Cargo targets map to %q", r.Name())
		}
		names[r.Name()] = r
	}
	if file == nil {
		return result, nil
	}
	for _, old := range file.Rules {
		owned := slices.Contains(old.Comments(), marker)
		fresh := names[old.Name()]
		if owned && !old.ShouldKeep() {
			for key := range kinds[old.Kind()].MergeableAttrs {
				if old.Attr(key) == nil || keptAttribute(old, key) {
					continue
				}
				var generated bzl.Expr
				if fresh != nil && fresh.Kind() == old.Kind() {
					generated = fresh.Attr(key)
				}
				if err := validateGeneratedMerge(old.Attr(key), generated); err != nil {
					return language.GenerateResult{}, fmt.Errorf("target %q attribute %s: %w", old.Name(), key, err)
				}
			}
		}
		if fresh != nil {
			if !owned {
				return language.GenerateResult{}, fmt.Errorf("target %q conflicts with a handwritten rule", old.Name())
			}
			if fresh.Kind() == old.Kind() {
				for key := range kinds[old.Kind()].MergeableAttrs {
					if old.Attr(key) != nil && fresh.Attr(key) == nil {
						fresh.SetAttr(key, generatedExpr{})
					}
				}
				continue
			}
		}
		if owned {
			empty := rule.NewRule(old.Kind(), old.Name())
			for key := range kinds[old.Kind()].MergeableAttrs {
				if old.Attr(key) != nil {
					empty.SetAttr(key, generatedExpr{})
				}
			}
			if fresh != nil {
				retained, err := removalRetainsRule(file, old, empty, kinds[old.Kind()])
				if err != nil {
					return language.GenerateResult{}, err
				}
				if retained {
					return language.GenerateResult{}, fmt.Errorf("target %q changes kind but a keep comment prevents removal", old.Name())
				}
			}
			result.Empty = append(result.Empty, empty)
		}
	}
	return result, nil
}

func keptAttribute(r *rule.Rule, key string) bool {
	if rule.ShouldKeep(r.Attr(key)) {
		return true
	}
	comments := r.AttrComments(key)
	return comments != nil && rule.ShouldKeep(&bzl.Ident{Comments: *comments})
}

// Check the empty merge on a copy before Gazelle changes any BUILD file.
func removalRetainsRule(file *rule.File, old, empty *rule.Rule, info rule.KindInfo) (bool, error) {
	snapshot, err := rule.LoadData(file.Path, file.Pkg, bzl.FormatWithoutRewriting(file.File))
	if err != nil {
		return false, fmt.Errorf("check removal of target %q: %w", old.Name(), err)
	}
	for _, candidate := range snapshot.Rules {
		if candidate.Name() != old.Name() || candidate.Kind() != old.Kind() {
			continue
		}
		rule.MergeRules(empty, candidate, info.MergeableAttrs, file.Path)
		return candidate.ShouldKeep() || !candidate.IsEmpty(info), nil
	}
	return false, fmt.Errorf("cannot check removal of target %q", old.Name())
}

// Remove deletion expressions after the first merge and before the second merge.
func clearDeletedAttrs(rules []*rule.Rule) {
	for _, r := range rules {
		for _, key := range r.AttrKeys() {
			if r.Attr(key) == nil {
				r.DelAttr(key)
			}
		}
	}
}

func (e *extension) OnResolve(ctx context.Context) error {
	clearDeletedAttrs(e.generated)
	return ctx.Err()
}

