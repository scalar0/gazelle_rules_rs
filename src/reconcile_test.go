// Protect kind changes when a keep comment prevents removal of the old rule.
// This catches partial old rules that block insertion of the new rule.
// The rule-level keep test does not cover attribute or item keep comments.
func TestKeptInputsBlockKindChanges(t *testing.T) {
	for _, declaration := range []struct{ name, input string }{
		{"attribute", "srcs = [\"src/lib.rs\"], # keep\n"},
		{"item", "srcs = [\n\"src/lib.rs\", # keep\n\"stale.rs\",\n],\n"},
	} {
		t.Run(declaration.name, func(t *testing.T) {
			root := t.TempDir()
			contents := marker + "\nrust_library(\nname = \"lib\",\n" + declaration.input + "deps = [\"//z:z\", \"//a:a\"],\n)\n"
			put(t, root, "second/BUILD.bazel", contents)
			file, err := rule.LoadFile(filepath.Join(root, "second/BUILD.bazel"), "second")
			if err != nil {
				t.Fatal(err)
			}
			before := string(bzl.FormatWithoutRewriting(file.File))
			fresh := newRule("alias", "lib")
			setAttr(fresh, "actual", ":context-library")
			if _, err := reconcile(file, []*rule.Rule{fresh}); err == nil || !strings.Contains(err.Error(), "prevents removal") {
				t.Fatalf("Expected a kept input conflict, got %v", err)
			}
			if string(bzl.FormatWithoutRewriting(file.File)) != before {
				t.Fatal("The removal check changed the parsed BUILD file.")
			}
			got, err := os.ReadFile(file.Path)
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != contents {
				t.Fatal("The removal check changed the BUILD file on disk.")
			}
		})
	}
}

// Protect keep comments in expressions that the generated merger cannot preserve.
// This catches silent removal of kept values inside an unknown function call.
// The list-item tests cover supported lists and conditional lists only.
func TestUnsupportedNestedKeepPreflight(t *testing.T) {
	for _, wholeAttribute := range []bool{false, true} {
		attributeKeep := ""
		if wholeAttribute {
			attributeKeep = " # keep"
		}
		file, err := rule.LoadData("BUILD.bazel", "probe", []byte(marker+`
rust_library(
    name = "lib",
    srcs = ["src/lib.rs"],
    deps = custom_deps([
        "//custom:kept", # keep
    ]),`+attributeKeep+`
)
`))
		if err != nil {
			t.Fatal(err)
		}
		before := string(file.Format())
		fresh := newRule("rust_library", "lib")
		setAttr(fresh, "srcs", librarySources("src/lib.rs"))
		setAttr(fresh, "deps", deps([]string{"normal"}))
		_, err = reconcile(file, []*rule.Rule{fresh})
		if wholeAttribute && err != nil {
			t.Fatalf("The preflight rejected a whole-attribute keep: %v", err)
		}
		if !wholeAttribute && (err == nil || !strings.Contains(err.Error(), "keep")) {
			t.Fatalf("Expected an unsupported keep error, got %v", err)
		}
		if string(file.Format()) != before {
			t.Fatal("The preflight changed the parsed BUILD file.")
		}
	}
}

