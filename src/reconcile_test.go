func TestContextCollapseRemovesSelection(t *testing.T) {
	file, err := rule.LoadData("BUILD.bazel", "crates/probe", []byte(`
# Generated by gazelle_rules_rs.
rust_doc_test(
    name = "probe-doc-tests",
    crate = ":probe",
    crate_features = select({"//conditions:default": ["old"]}),
    target_compatible_with = select({"//conditions:default": []}), # keep
)
`))
	if err != nil {
		t.Fatal(err)
	}
	fresh := newRule("rust_doc_test", "probe-doc-tests")
	setAttr(fresh, "crate", ":probe")
	result, err := reconcile(file, []*rule.Rule{fresh})
	if err != nil {
		t.Fatal(err)
	}
	if err := merger.MergeFile(merger.MergeFileArgs{File: file, Empty: result.Empty, Gen: result.Gen, Phase: merger.PreResolve, GetKindInfo: func(r *rule.Rule) rule.KindInfo { return kindMap()[r.Kind()] }}); err != nil {
		t.Fatal(err)
	}
	if file.Rules[0].Attr("crate_features") != nil {
		t.Fatal("The old feature selection must be removed.")
	}
	if file.Rules[0].Attr("target_compatible_with") == nil {
		t.Fatal("The kept compatibility selection must remain.")
	}
}
